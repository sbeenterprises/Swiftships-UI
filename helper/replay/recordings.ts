/** Mission Replay - recording store
 *
 * Persists mission recordings captured by the UI as NDJSON files under
 * `{configPath}/swiftships-recordings/`.
 *
 * Each recording is two files:
 *  - `{id}.meta.json`   the manifest
 *  - `{id}.ndjson`      one event per line:
 *                       {"t":<ms since start>,"k":"sk"|"moos","d":<delta|string>}
 *
 * Routes are mounted twice by helper/index.ts:
 *  - `/signalk/v1/api/swiftships/recordings` (via plugin.signalKApiRoutes) - what
 *    the UI uses. `/signalk/v1/api/*` only requires an authorised principal, and
 *    with `allow_readonly` that includes anonymous sessions. PUT is the one method
 *    the server gates separately, so this API never uses it.
 *  - `/plugins/{id}/recordings` (via plugin.registerWithRouter) - admin only,
 *    handy for curl/debugging.
 * ************************************/

import { IRouter, Request, Response } from 'express';
import * as fs from 'fs';
import * as path from 'path';

const RECORDINGS_DIR = 'swiftships-recordings';
const ID_PATTERN = /^rec-[a-z0-9-]+$/;
/** a recording still flagged `recording` whose file is older than this is assumed abandoned */
const INTERRUPT_AFTER_MS = 2 * 60 * 1000;

export type RecordingStatus = 'recording' | 'complete' | 'interrupted';

export interface RecordingMeta {
  id: string;
  name: string;
  notes?: string;
  startedAt: string;
  endedAt?: string;
  durationMs: number;
  eventCount: number;
  sizeBytes: number;
  selfId?: string;
  vesselName?: string;
  status: RecordingStatus;
  /** next expected chunk sequence number - gives chunk uploads idempotency */
  nextSeq: number;
}

interface RecordingsHost {
  config: { configPath: string };
  debug: (msg: string) => void;
  error: (msg: string) => void;
}

export const initRecordings = (server: RecordingsHost) => {
  const baseDir = path.join(server.config.configPath, RECORDINGS_DIR);

  const ensureDir = () => {
    if (!fs.existsSync(baseDir)) {
      fs.mkdirSync(baseDir, { recursive: true });
    }
  };

  const metaPath = (id: string) => path.join(baseDir, `${id}.meta.json`);
  const dataPath = (id: string) => path.join(baseDir, `${id}.ndjson`);

  const newId = () =>
    `rec-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;

  /** guards against path traversal - ids are generated by newId() and never contain dots */
  const validId = (id: unknown): id is string =>
    typeof id === 'string' && ID_PATTERN.test(id);

  const readMeta = (id: string): RecordingMeta | null => {
    try {
      return JSON.parse(fs.readFileSync(metaPath(id), 'utf8')) as RecordingMeta;
    } catch (e) {
      return null;
    }
  };

  const writeMeta = (meta: RecordingMeta) => {
    fs.writeFileSync(metaPath(meta.id), JSON.stringify(meta, null, 2), 'utf8');
  };

  const sizeOf = (id: string): number => {
    try {
      return fs.statSync(dataPath(id)).size;
    } catch (e) {
      return 0;
    }
  };

  /** scan an abandoned recording's data file to recover eventCount and durationMs */
  const scanTail = (id: string): { eventCount: number; durationMs: number } => {
    let eventCount = 0;
    let durationMs = 0;
    try {
      const raw = fs.readFileSync(dataPath(id), 'utf8');
      let from = 0;
      let lastStart = -1;
      for (;;) {
        const nl = raw.indexOf('\n', from);
        if (nl === -1) {
          break;
        }
        if (nl > from) {
          eventCount++;
          lastStart = from;
        }
        from = nl + 1;
      }
      if (from < raw.length) {
        eventCount++;
        lastStart = from;
      }
      if (lastStart !== -1) {
        const last = JSON.parse(raw.slice(lastStart).trim());
        durationMs = typeof last.t === 'number' ? last.t : 0;
      }
    } catch (e) {
      server.debug(`Could not scan recording ${id}: ${e}`);
    }
    return { eventCount, durationMs };
  };

  /**
   * Recover recordings the browser abandoned mid-capture (closing the tab is the
   * common case). They must remain fully playable.
   */
  const repairIfStale = (meta: RecordingMeta): RecordingMeta => {
    if (meta.status !== 'recording') {
      return meta;
    }
    let mtime = 0;
    try {
      mtime = fs.statSync(dataPath(meta.id)).mtimeMs;
    } catch (e) {
      mtime = Date.parse(meta.startedAt) || 0;
    }
    if (Date.now() - mtime < INTERRUPT_AFTER_MS) {
      return meta;
    }
    const { eventCount, durationMs } = scanTail(meta.id);
    const repaired: RecordingMeta = {
      ...meta,
      status: 'interrupted',
      eventCount,
      durationMs,
      sizeBytes: sizeOf(meta.id),
      endedAt: new Date(mtime).toISOString()
    };
    writeMeta(repaired);
    server.debug(`Repaired interrupted recording ${meta.id}`);
    return repaired;
  };

  const listRecordings = (): RecordingMeta[] => {
    ensureDir();
    return fs
      .readdirSync(baseDir)
      .filter((f) => f.endsWith('.meta.json'))
      .map((f) => readMeta(f.slice(0, -'.meta.json'.length)))
      .filter((m): m is RecordingMeta => m !== null)
      .map(repairIfStale)
      .sort((a, b) => b.startedAt.localeCompare(a.startedAt));
  };

  /** attaches every route to the supplied router - called once per mount point */
  const registerRoutes = (router: IRouter): IRouter => {
    const withMeta =
      (handler: (meta: RecordingMeta, req: Request, res: Response) => void) =>
      (req: Request, res: Response) => {
        const id = req.params.id;
        if (!validId(id)) {
          res.status(400).json({ message: 'Invalid recording id.' });
          return;
        }
        const meta = readMeta(id);
        if (!meta) {
          res.status(404).json({ message: 'Recording not found.' });
          return;
        }
        handler(meta, req, res);
      };

    router.get('/swiftships/recordings', (req: Request, res: Response) => {
      try {
        res.status(200).json(listRecordings());
      } catch (e) {
        server.error(`recordings list failed: ${e}`);
        res.status(500).json({ message: 'Could not list recordings.' });
      }
    });

    router.post('/swiftships/recordings', (req: Request, res: Response) => {
      try {
        ensureDir();
        const body = req.body ?? {};
        const meta: RecordingMeta = {
          id: newId(),
          name: (body.name || '').toString().slice(0, 120) || 'Mission',
          startedAt: body.startedAt || new Date().toISOString(),
          durationMs: 0,
          eventCount: 0,
          sizeBytes: 0,
          selfId: body.selfId,
          vesselName: body.vesselName,
          status: 'recording',
          nextSeq: 0
        };
        fs.writeFileSync(dataPath(meta.id), '', 'utf8');
        writeMeta(meta);
        server.debug(`Started recording ${meta.id}`);
        res.status(201).json(meta);
      } catch (e) {
        server.error(`recording create failed: ${e}`);
        res.status(500).json({ message: 'Could not create recording.' });
      }
    });

    /**
     * Append a batch of events.
     * Body is `{seq, lines}` where `lines` is a raw NDJSON blob, so the server
     * never parses the events themselves - it appends the string verbatim.
     * `seq` makes retries safe: a retry that actually succeeded replays as
     * `seq === nextSeq - 1` and is acknowledged as a duplicate rather than
     * appended twice.
     */
    router.post(
      '/swiftships/recordings/:id/chunk',
      withMeta((meta, req, res) => {
        const seq = Number(req.body?.seq);
        const lines: string = req.body?.lines ?? '';
        if (!Number.isInteger(seq) || seq < 0) {
          res.status(400).json({ message: 'Invalid seq.' });
          return;
        }
        if (seq === meta.nextSeq - 1) {
          res.status(200).json({ duplicate: true, nextSeq: meta.nextSeq });
          return;
        }
        if (seq !== meta.nextSeq) {
          res
            .status(409)
            .json({ message: 'Out of sequence.', nextSeq: meta.nextSeq });
          return;
        }
        try {
          if (lines.length !== 0) {
            fs.appendFileSync(
              dataPath(meta.id),
              lines.endsWith('\n') ? lines : lines + '\n',
              'utf8'
            );
          }
          meta.nextSeq = seq + 1;
          meta.sizeBytes = sizeOf(meta.id);
          if (typeof req.body?.eventCount === 'number') {
            meta.eventCount += req.body.eventCount;
          }
          if (typeof req.body?.durationMs === 'number') {
            meta.durationMs = req.body.durationMs;
          }
          writeMeta(meta);
          res.status(200).json({ nextSeq: meta.nextSeq });
        } catch (e) {
          server.error(`recording chunk append failed: ${e}`);
          res.status(500).json({ message: 'Could not append chunk.' });
        }
      })
    );

    router.post(
      '/swiftships/recordings/:id/finalize',
      withMeta((meta, req, res) => {
        try {
          meta.status = 'complete';
          meta.endedAt = req.body?.endedAt || new Date().toISOString();
          if (typeof req.body?.durationMs === 'number') {
            meta.durationMs = req.body.durationMs;
          }
          if (typeof req.body?.eventCount === 'number') {
            meta.eventCount = req.body.eventCount;
          }
          meta.sizeBytes = sizeOf(meta.id);
          writeMeta(meta);
          server.debug(`Finalized recording ${meta.id}`);
          res.status(200).json(meta);
        } catch (e) {
          server.error(`recording finalize failed: ${e}`);
          res.status(500).json({ message: 'Could not finalize recording.' });
        }
      })
    );

    // POST rather than PUT: `/signalk/v1/*` gates PUT behind write auth.
    router.post(
      '/swiftships/recordings/:id/rename',
      withMeta((meta, req, res) => {
        try {
          if (typeof req.body?.name === 'string') {
            meta.name = req.body.name.slice(0, 120);
          }
          if (typeof req.body?.notes === 'string') {
            meta.notes = req.body.notes.slice(0, 2000);
          }
          writeMeta(meta);
          res.status(200).json(meta);
        } catch (e) {
          server.error(`recording rename failed: ${e}`);
          res.status(500).json({ message: 'Could not rename recording.' });
        }
      })
    );

    router.get(
      '/swiftships/recordings/:id/meta',
      withMeta((meta, req, res) => {
        res.status(200).json(repairIfStale(meta));
      })
    );

    router.get(
      '/swiftships/recordings/:id/events',
      withMeta((meta, req, res) => {
        const size = sizeOf(meta.id);
        const fromByte = Math.max(0, Number(req.query.fromByte ?? 0) || 0);
        const toByte = req.query.toByte
          ? Math.min(size - 1, Number(req.query.toByte))
          : size - 1;
        res.type('application/x-ndjson');
        if (size === 0 || toByte < fromByte) {
          res.status(200).send('');
          return;
        }
        const rs = fs.createReadStream(dataPath(meta.id), {
          start: fromByte,
          end: toByte
        });
        rs.on('error', (e) => {
          server.error(`recording read failed: ${e}`);
          if (!res.headersSent) {
            res.status(500).json({ message: 'Could not read recording.' });
          }
        });
        rs.pipe(res);
      })
    );

    const doDelete = withMeta((meta, req, res) => {
      try {
        [metaPath(meta.id), dataPath(meta.id)].forEach((f) => {
          if (fs.existsSync(f)) {
            fs.unlinkSync(f);
          }
        });
        server.debug(`Deleted recording ${meta.id}`);
        res.status(200).json({ id: meta.id, deleted: true });
      } catch (e) {
        server.error(`recording delete failed: ${e}`);
        res.status(500).json({ message: 'Could not delete recording.' });
      }
    });

    // The server registers its own `app.delete('/signalk/v1/api/*')` catch-all
    // (src/put.js) before plugins load, so a real DELETE never reaches us on
    // that mount - it 403s for read-only sessions. POST is the usable verb
    // there, same reason rename is a POST.
    router.post('/swiftships/recordings/:id/delete', doDelete);
    // still works on the admin /plugins mount
    router.delete('/swiftships/recordings/:id', doDelete);

    return router;
  };

  return { registerRoutes, listRecordings };
};
